// ---- Systems library -----------------------------------------------------
const SYS = path.join(ROOT, 'systems');
const ORDER = ['offense', 'defense', 'transition', 'concepts', 'actions', 'special-situations'];
const folders = fs.readdirSync(SYS, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name)
  .sort((a, b) => (ORDER.indexOf(a) + 1 || 99) - (ORDER.indexOf(b) + 1 || 99) || a.localeCompare(b));
let systemsCount = 0;
const systemSections = folders.map(folder => {
  const files = fs.readdirSync(path.join(SYS, folder)).filter(f => f.endsWith('.md')).sort();
  systemsCount += files.length;
  return {
    heading: titleCase(folder),
    items: files.map(f => {
      const rel = `systems/${folder}/${f}`;
      const d = describe(path.join(ROOT, rel));
      return { title: d.title, summary: d.summary, href: `/doc.html?f=${encodeURIComponent(rel)}` };
    })
  };
}).filter(s => s.items.length);
fs.writeFileSync(path.join(SYS, 'index.html'), page({
  title: 'Systems Library',
  intro: `${systemsCount} documents on offense, defense, transition, concepts, actions and special situations.`,
  sections: systemSections
}));
console.log(`✅ systems/index.html (${systemsCount} documents)`);

// ---- Templates -------------------------------------------------------------
const TPL = path.join(ROOT, 'templates');
const tplFiles = fs.readdirSync(TPL).filter(f => !f.startsWith('.') && f !== 'index.html').sort();
const tplItems = tplFiles.map(f => {
  const rel = `templates/${f}`;
  if (f.endsWith('.md')) {
    const d = describe(path.join(ROOT, rel));
    return { title: d.title, summary: d.summary, href: `/doc.html?f=${encodeURIComponent(rel)}`, tag: 'Markdown template' };
  }
  const ext = path.extname(f).slice(1).toUpperCase();
  return { title: path.basename(f, path.extname(f)), summary: '', href: '/' + rel.split('/').map(encodeURIComponent).join('/'),
    tag: ext === 'DOCX' ? 'Word document (download)' : ext + ' file', download: ext === 'DOCX' };
});
fs.writeFileSync(path.join(TPL, 'index.html'), page({
  title: 'Templates',
  intro: 'Scout report, opponent profile, practice plan and player card templates.',
  sections: [{ heading: 'Templates', items: tplItems }]
}));
console.log(`✅ templates/index.html (${tplItems.length} files)`);
