// Builds the index pages for the Systems library (systems/index.html) and the
// Templates folder (templates/index.html), so the "Systems" and "Templates"
// links on the site open a browsable list instead of "Page not found".
// Each Markdown document links to /doc.html, which shows it as a readable page.
// Runs on every Netlify build (see package.json), so new files appear by themselves.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');

function esc(s) {
  return String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
}

function titleCase(slug) {
  return slug.replace(/[-_]+/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
}

// Title = first "# " heading; summary = first plain paragraph line.
function describe(file) {
  const text = fs.readFileSync(file, 'utf8');
  const h1 = (text.match(/^#\s+(.+)$/m) || [])[1];
  const summary = text.split('\n').map(l => l.trim())
    .find(l => l && !/^(#|\||>|-{3,}|\*\*[^*]+:\*\*\s*$|[-*+]\s|\d+\.\s|```)/.test(l)) || '';
  return {
    title: (h1 || titleCase(path.basename(file, '.md'))).replace(/\*\*/g, ''),
    summary: summary.replace(/\*\*|__|`/g, '').replace(/\[([^\]]+)\]\([^)]+\)/g, '$1').slice(0, 170)
  };
}

